#!/usr/bin/env python3
"""Regenerates every Oracle script and the single install file.
    python3 tools/database/build_all.py

  02_seed_data.sql            <- build_oracle_seed.py
  03_comments_and_triggers.sql <- build_oracle_comments.py
  04_integrity_rules.sql      <- build_oracle_integrity.py (reads 01_create_tables.sql)
  IB_PROCESS_install.sql      =  01 + 02 + 03 + 04, in that order (run it as the schema owner)

All scripts are kept in plain ASCII so they run the same in SQL Developer, SQL*Plus or SQLcl whatever the client
encoding is.
"""
import os, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
ORA = os.path.join(ROOT, "database", "oracle")
PARTS = ["01_create_tables.sql", "02_seed_data.sql", "03_comments_and_triggers.sql", "04_integrity_rules.sql"]
ASCII = {"·": "-", "→": "->", "←": "<-", "↔": "<->", "—": "-", "–": "-", "×": "x", "≤": "<=", "≥": ">=", "“": '"', "”": '"', "’": "'",
         "á": "a", "é": "e", "í": "i", "ó": "o", "ú": "u", "ñ": "n", "Á": "A", "É": "E", "Í": "I", "Ó": "O", "Ú": "U", "Ñ": "N"}

for script in ("build_oracle_seed.py", "build_oracle_comments.py", "build_oracle_integrity.py"):
    subprocess.run([sys.executable, os.path.join(HERE, script)], check=True)

texts = []
for name in PARTS:
    path = os.path.join(ORA, name)
    text = open(path, encoding="utf8").read()
    for k, v in ASCII.items():
        text = text.replace(k, v)
    if "&" in text:
        sys.exit(f"{name}: '&' would be read as a substitution variable by SQL*Plus / SQL Developer")
    bad = sorted({c for c in text if ord(c) > 127})
    if bad:
        sys.exit(f"{name}: non-ASCII characters left: {bad}")
    open(path, "w", encoding="ascii", newline="\n").write(text)
    texts.append(f"-- ==================================================================== {name}\n" + text.rstrip() + "\n")

header = ["/* =====================================================================",
          "   Expo and Return FG Follow Up (IB Process) - JuP1 (8640) - ME/QMM",
          "   SINGLE INSTALL SCRIPT = 01_create_tables + 02_seed_data + 03_comments_and_triggers + 04_integrity_rules",
          "   Generated by tools/database/build_all.py. Run once, connected as the owner of the schema",
          "   (SQL Developer: Run Script F5 - SQL*Plus / SQLcl: @IB_PROCESS_install.sql).",
          "   ===================================================================== */", "",
          "SET DEFINE OFF",
          "SET SQLBLANKLINES ON",
          "WHENEVER SQLERROR EXIT ROLLBACK", ""]
out = os.path.join(ORA, "IB_PROCESS_install.sql")
open(out, "w", encoding="ascii", newline="\n").write("\n".join(header) + "\n".join(texts))
print("OK ->", os.path.relpath(out, ROOT))
