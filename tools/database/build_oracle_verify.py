#!/usr/bin/env python3
"""Generates database/oracle/90_verify_install.sql: compares what the schema really has (Oracle data dictionary)
with what 01-04 define, and returns ONLY the differences. "no rows selected" in sections 1-4 = identical.
    python3 tools/database/build_oracle_verify.py      (also run by build_all.py)
"""
import os, re
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
ORA = os.path.join(ROOT, "database", "oracle")
OUT = os.path.join(ORA, "90_verify_install.sql")

def read(name): return open(os.path.join(ORA, name), encoding="utf8").read()
def nocomments(sql): return re.sub(r"--[^\n]*", "", re.sub(r"/\*.*?\*/", "", sql, flags=re.S))
def q(s): return "'" + s.replace("'", "''") + "'"

ddl = nocomments(read("01_create_tables.sql"))
columns, constraints, indexes = [], [], []
for m in re.finditer(r"CREATE TABLE (IB_PROCESS_\w+) \((.*?)\n\);", ddl, re.S):
    table, body = m.group(1), m.group(2)
    pk_cols = set()
    pk = re.search(r"PRIMARY KEY \(([^)]*)\)", body)
    if pk: pk_cols = {c.strip() for c in pk.group(1).split(",")}
    defs, current = [], None
    for line in body.splitlines():
        if re.match(r"^ {4}[A-Z]", line):
            current = [line.strip()]; defs.append(current)
        elif current is not None and line.strip():
            current.append(line.strip())
    for d in defs:
        text = " ".join(d)
        if text.startswith("CONSTRAINT"):
            name = text.split()[1]
            kind = "P" if "PRIMARY KEY" in text else "U" if " UNIQUE " in text + " " else "R" if "FOREIGN KEY" in text else "C"
            constraints.append((table, name, f"{kind} ENABLED VALIDATED"))
            if kind in "PU": indexes.append((table, name, "UNIQUE VALID"))
            continue
        col = text.split()[0]
        t = re.match(r"^\w+\s+([A-Z0-9]+)(?:\((\d+)(?:,(\d+))?( CHAR)?\))?", text)
        base, n, scale, char = t.group(1), t.group(2), t.group(3), t.group(4)
        if base == "VARCHAR2": desc = f"VARCHAR2({n} {'C' if char else 'B'})"
        elif base in ("NVARCHAR2", "CHAR"): desc = f"{base}({n})"
        elif base == "NUMBER": desc = f"NUMBER({n},{scale or 0})" if n else "NUMBER"
        elif base == "TIMESTAMP": desc = "TIMESTAMP(6)"
        else: desc = base
        nullable = "N" if ("NOT NULL" in text or "IDENTITY" in text or col in pk_cols) else "Y"
        columns.append((table, col, f"{desc} {nullable}"))
for m in re.finditer(r"CREATE (UNIQUE )?INDEX (\w+) ON (\w+)", ddl):
    indexes.append((m.group(3), m.group(2), ("UNIQUE" if m.group(1) else "NONUNIQUE") + " VALID"))

triggers = []
for m in re.finditer(r"CREATE OR REPLACE TRIGGER (\w+)\s+BEFORE [A-Z ]+? ON (\w+)", read("03_comments_and_triggers.sql") + read("04_integrity_rules.sql")):
    triggers.append((m.group(1), m.group(2), f"{m.group(2)} ENABLED VALID"))

seed = read("02_seed_data.sql")
tables = [c[0] for c in columns]
tables = list(dict.fromkeys(tables))
counts = {t: len(re.findall(rf"^INSERT INTO {t} ", seed, re.M)) for t in tables}

def values(rows, cols):
    lines = [f"    SELECT {', '.join(q(v) for v in r)} FROM DUAL" for r in rows]
    return f"expected ({', '.join(cols)}) AS (\n" + " UNION ALL\n".join(lines) + "\n)"

LIKE = "LIKE 'IB\\_PROCESS\\_%' ESCAPE '\\'"
L = ["/* =====================================================================",
     "   Expo and Return FG Follow Up (IB Process) - Oracle - Script 90: verify the installation",
     "   Generated by tools/database/build_oracle_verify.py from scripts 01-04. Read only (only SELECT).",
     "   Run with Run Script (F5). Sections 1 to 4 list ONLY differences between the database and the scripts:",
     "   'no rows selected' in all four = the schema is exactly what the scripts define.",
     f"   Expected: {len(tables)} tables, {len(columns)} columns, {len(constraints)} named constraints, "
     f"{len(indexes)} indexes, {len(triggers)} triggers.",
     "   ===================================================================== */", "",
     "SET DEFINE OFF", "",
     f"PROMPT 1. Columns (type, length in characters C / bytes B, nullable Y/N) - only differences",
     "WITH " + values(columns, ["TABLE_NAME", "COLUMN_NAME", "DESCRIPTOR"]) + ",",
     "actual AS (",
     "    SELECT TABLE_NAME, COLUMN_NAME,",
     "           CASE WHEN DATA_TYPE = 'VARCHAR2' THEN 'VARCHAR2(' || CHAR_LENGTH || ' ' || CHAR_USED || ')'",
     "                WHEN DATA_TYPE IN ('NVARCHAR2', 'CHAR') THEN DATA_TYPE || '(' || CHAR_LENGTH || ')'",
     "                WHEN DATA_TYPE = 'NUMBER' AND DATA_PRECISION IS NOT NULL THEN 'NUMBER(' || DATA_PRECISION || ',' || NVL(DATA_SCALE, 0) || ')'",
     "                ELSE DATA_TYPE END || ' ' || NULLABLE AS DESCRIPTOR",
     f"      FROM USER_TAB_COLUMNS WHERE TABLE_NAME {LIKE}",
     ")",
     "SELECT NVL(e.TABLE_NAME, a.TABLE_NAME) AS TABLE_NAME, NVL(e.COLUMN_NAME, a.COLUMN_NAME) AS COLUMN_NAME,",
     "       e.DESCRIPTOR AS EXPECTED, a.DESCRIPTOR AS IN_DATABASE",
     "  FROM expected e FULL OUTER JOIN actual a ON a.TABLE_NAME = e.TABLE_NAME AND a.COLUMN_NAME = e.COLUMN_NAME",
     " WHERE e.DESCRIPTOR IS NULL OR a.DESCRIPTOR IS NULL OR e.DESCRIPTOR <> a.DESCRIPTOR",
     " ORDER BY 1, 2;", "",
     "PROMPT 2. Named constraints (P primary key, U unique, R foreign key, C check; enabled and validated) - only differences",
     "WITH " + values(constraints, ["TABLE_NAME", "CONSTRAINT_NAME", "DESCRIPTOR"]) + ",",
     "actual AS (",
     "    SELECT TABLE_NAME, CONSTRAINT_NAME, CONSTRAINT_TYPE || ' ' || STATUS || ' ' || VALIDATED AS DESCRIPTOR",
     f"      FROM USER_CONSTRAINTS WHERE TABLE_NAME {LIKE} AND CONSTRAINT_NAME NOT LIKE 'SYS\\_%' ESCAPE '\\'",
     ")",
     "SELECT NVL(e.TABLE_NAME, a.TABLE_NAME) AS TABLE_NAME, NVL(e.CONSTRAINT_NAME, a.CONSTRAINT_NAME) AS CONSTRAINT_NAME,",
     "       e.DESCRIPTOR AS EXPECTED, a.DESCRIPTOR AS IN_DATABASE",
     "  FROM expected e FULL OUTER JOIN actual a ON a.CONSTRAINT_NAME = e.CONSTRAINT_NAME",
     " WHERE e.DESCRIPTOR IS NULL OR a.DESCRIPTOR IS NULL OR e.DESCRIPTOR <> a.DESCRIPTOR OR e.TABLE_NAME <> a.TABLE_NAME",
     " ORDER BY 1, 2;", "",
     "PROMPT 3. Indexes (unique or not, valid) - only differences",
     "WITH " + values(indexes, ["TABLE_NAME", "INDEX_NAME", "DESCRIPTOR"]) + ",",
     "actual AS (",
     "    SELECT TABLE_NAME, INDEX_NAME, UNIQUENESS || ' ' || STATUS AS DESCRIPTOR",
     f"      FROM USER_INDEXES WHERE TABLE_NAME {LIKE} AND INDEX_NAME NOT LIKE 'SYS\\_%' ESCAPE '\\'",
     ")",
     "SELECT NVL(e.TABLE_NAME, a.TABLE_NAME) AS TABLE_NAME, NVL(e.INDEX_NAME, a.INDEX_NAME) AS INDEX_NAME,",
     "       e.DESCRIPTOR AS EXPECTED, a.DESCRIPTOR AS IN_DATABASE",
     "  FROM expected e FULL OUTER JOIN actual a ON a.INDEX_NAME = e.INDEX_NAME",
     " WHERE e.DESCRIPTOR IS NULL OR a.DESCRIPTOR IS NULL OR e.DESCRIPTOR <> a.DESCRIPTOR",
     " ORDER BY 1, 2;", "",
     "PROMPT 4. Triggers (table or SCHEMA, enabled, compiled without errors) - only differences",
     "WITH " + values(triggers, ["TRIGGER_NAME", "TABLE_NAME", "DESCRIPTOR"]) + ",",
     "actual AS (",
     "    SELECT t.TRIGGER_NAME, NVL(t.TABLE_NAME, TRIM(t.BASE_OBJECT_TYPE)) AS TABLE_NAME,",
     "           NVL(t.TABLE_NAME, TRIM(t.BASE_OBJECT_TYPE)) || ' ' || t.STATUS || ' ' || o.STATUS AS DESCRIPTOR",
     "      FROM USER_TRIGGERS t JOIN USER_OBJECTS o ON o.OBJECT_NAME = t.TRIGGER_NAME AND o.OBJECT_TYPE = 'TRIGGER'",
     "     WHERE t.TRIGGER_NAME LIKE 'IB\\_%' ESCAPE '\\'",
     ")",
     "SELECT NVL(e.TRIGGER_NAME, a.TRIGGER_NAME) AS TRIGGER_NAME, e.DESCRIPTOR AS EXPECTED, a.DESCRIPTOR AS IN_DATABASE",
     "  FROM expected e FULL OUTER JOIN actual a ON a.TRIGGER_NAME = e.TRIGGER_NAME",
     " WHERE e.DESCRIPTOR IS NULL OR a.DESCRIPTOR IS NULL OR e.DESCRIPTOR <> a.DESCRIPTOR",
     " ORDER BY 1;", "",
     "PROMPT 5. Rows per table (information: right after the install the two columns are equal; later the app adds rows)",
     " UNION ALL\n".join(f"SELECT {q(t)} AS TABLE_NAME, {counts[t]} AS ROWS_AT_INSTALL, (SELECT COUNT(*) FROM {t}) AS ROWS_NOW FROM DUAL"
                         for t in tables) + ";", "",
     "PROMPT 6. Totals",
     f"SELECT (SELECT COUNT(*) FROM USER_TABLES WHERE TABLE_NAME {LIKE}) AS TABLES_{len(tables)},",
     f"       (SELECT COUNT(*) FROM USER_TAB_COLUMNS WHERE TABLE_NAME {LIKE}) AS COLUMNS_{len(columns)},",
     f"       (SELECT COUNT(*) FROM USER_CONSTRAINTS WHERE TABLE_NAME {LIKE} AND CONSTRAINT_NAME NOT LIKE 'SYS\\_%' ESCAPE '\\') AS CONSTRAINTS_{len(constraints)},",
     f"       (SELECT COUNT(*) FROM USER_INDEXES WHERE TABLE_NAME {LIKE} AND INDEX_NAME NOT LIKE 'SYS\\_%' ESCAPE '\\') AS INDEXES_{len(indexes)},",
     f"       (SELECT COUNT(*) FROM USER_TRIGGERS WHERE TRIGGER_NAME LIKE 'IB\\_%' ESCAPE '\\' AND STATUS = 'ENABLED') AS TRIGGERS_{len(triggers)},",
     "       (SELECT COUNT(*) FROM USER_OBJECTS WHERE OBJECT_NAME LIKE 'IB\\_%' ESCAPE '\\' AND STATUS <> 'VALID') AS INVALID_0",
     "  FROM DUAL;", ""]
open(OUT, "w", encoding="ascii", newline="\n").write("\n".join(L))
print(f"OK -> {os.path.relpath(OUT, ROOT)} ({len(tables)} tables, {len(columns)} columns, {len(constraints)} constraints, "
      f"{len(indexes)} indexes, {len(triggers)} triggers)")
