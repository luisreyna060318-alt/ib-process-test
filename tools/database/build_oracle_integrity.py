#!/usr/bin/env python3
"""Generates database/oracle/04_integrity_rules.sql from 01_create_tables.sql:
  * NO DELETE on any IB_PROCESS_ table (not even the Owner, not even the schema owner while the triggers are enabled).
  * A column that already has a value can be changed but never emptied (NOT NULL -> NULL is refused).
    Columns calculated by the application (they follow other fields) are excluded.
  * DROP / TRUNCATE of IB_PROCESS_ objects is refused (schema DDL trigger).
    python3 tools/database/build_oracle_integrity.py
"""
import os, re
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DDL = os.path.join(ROOT, "database", "oracle", "01_create_tables.sql")
OUT = os.path.join(ROOT, "database", "oracle", "04_integrity_rules.sql")

# Calculated by the application from other fields: they may legitimately go back to NULL.
CALCULATED = {
    "IB_PROCESS_PALLET_RETURNS": {"MM60_UNIT_COST_USD", "DUTY_RISK_REASON", "LEGAL_DUE_DATE", "DATA_QUALITY_FLAGS"},
}

def tables():
    sql = open(DDL, encoding="utf8").read()
    for m in re.finditer(r"CREATE TABLE (\w+) \((.*?)\n\);", sql, re.S):
        name, body = m.group(1), m.group(2)
        abbr = re.search(r"CONSTRAINT (\w+)_PK PRIMARY KEY", body).group(1)
        nullable = []
        for line in body.splitlines():
            line = re.sub(r"--.*$", "", line).strip()
            if not line or line.startswith(("CONSTRAINT", "/*", "OR ", "AND ")) or not re.match(r"^[A-Z_0-9]+\s+[A-Z]", line):
                continue
            col = line.split()[0]
            if "NOT NULL" in line or "VIRTUAL" in line or "IDENTITY" in line:
                continue
            nullable.append(col)
        yield name, abbr, [c for c in nullable if c not in CALCULATED.get(name, set())]

L = ["/* =====================================================================",
     "   Expo & Return FG Follow Up (IB Process) · Oracle · Script 04: data integrity rules",
     "   Generated by tools/database/build_oracle_integrity.py from 01_create_tables.sql.",
     "   1. Nothing is deleted: DELETE is refused on every IB_PROCESS_ table (also for the Owner).",
     "      Access that ends is closed with VALID_TO / REMOVED_BY; a request is APPROVED or REJECTED.",
     "   2. A value already captured can be changed but never emptied (NOT NULL -> NULL is refused).",
     "   3. DROP / TRUNCATE of IB_PROCESS_ objects is refused.",
     "   For planned maintenance only: ALTER TRIGGER <name> DISABLE; ... ALTER TRIGGER <name> ENABLE;",
     "   ===================================================================== */", ""]
for name, abbr, cols in tables():
    if name != "IB_PROCESS_AUDIT_LOG":      # already covered by IB_PROCESS_AUDIT_LOG_RO (script 03)
        L += [f"CREATE OR REPLACE TRIGGER {abbr}_NO_DELETE",
              f"BEFORE DELETE ON {name}",
              "BEGIN",
              f"    RAISE_APPLICATION_ERROR(-20010, '{name}: records are never deleted.');",
              "END;", "/", ""]
    if cols:
        L += [f"CREATE OR REPLACE TRIGGER {abbr}_NO_EMPTY",
              f"BEFORE UPDATE ON {name}",
              "FOR EACH ROW",
              "BEGIN"]
        for c in cols:
            L.append(f"    IF :OLD.{c} IS NOT NULL AND :NEW.{c} IS NULL THEN "
                     f"RAISE_APPLICATION_ERROR(-20011, '{name}.{c} has a value and cannot be emptied.'); END IF;")
        L += ["END;", "/", ""]

L += ["-- DROP / TRUNCATE of the application objects (run as the schema owner).",
      "CREATE OR REPLACE TRIGGER IB_PROCESS_NO_DROP",
      "BEFORE DROP OR TRUNCATE ON SCHEMA",
      "BEGIN",
      "    IF ORA_DICT_OBJ_NAME LIKE 'IB\\_PROCESS\\_%' ESCAPE '\\' OR ORA_DICT_OBJ_NAME LIKE 'IB\\_%' ESCAPE '\\' THEN",
      "        RAISE_APPLICATION_ERROR(-20012, ORA_DICT_OBJ_NAME || ': IB_PROCESS objects are never dropped or truncated.');",
      "    END IF;",
      "END;", "/", "",
      "/* Application account (if it is not the schema owner): read / insert / update only, never DELETE.",
      "   Replace APP_USER with the user returned by SharedServersAccess for IFACTJUP.",
      "BEGIN",
      "    FOR t IN (SELECT TABLE_NAME FROM USER_TABLES WHERE TABLE_NAME LIKE 'IB\\_PROCESS\\_%' ESCAPE '\\') LOOP",
      "        EXECUTE IMMEDIATE 'GRANT SELECT, INSERT, UPDATE ON ' || t.TABLE_NAME || ' TO APP_USER';",
      "    END LOOP;",
      "END;",
      "/",
      "*/", ""]
open(OUT, "w", encoding="utf8").write("\n".join(L))
print("OK ->", os.path.relpath(OUT, ROOT))
