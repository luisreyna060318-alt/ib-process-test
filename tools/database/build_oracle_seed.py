#!/usr/bin/env python3
"""Generates database/oracle/02_seed_data.sql (catalog rows, field permissions, parameters, first Owner).
    python3 tools/database/build_oracle_seed.py
"""
import os
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "database", "oracle", "02_seed_data.sql")

def q(v):
    if v is None: return "NULL"
    if isinstance(v, (int, float)): return str(v)
    return "'" + str(v).replace("'", "''") + "'"

L = []
def ins(table, cols, rows):
    for r in rows:
        L.append(f"INSERT INTO {table} ({', '.join(cols)}) VALUES ({', '.join(q(v) for v in r)});")
    L.append("")

L += ["/* =====================================================================",
      "   Expo & Return FG Follow Up (IB Process) · Oracle · Script 02: seed data",
      "   Generated by tools/database/build_oracle_seed.py. Run after 01_create_tables.sql.",
      "   ===================================================================== */", ""]

L.append("-- Value Streams")
ins("IB_PROCESS_VALUE_STREAMS", ["VALUE_STREAM_ID", "CODE", "NAME", "SHEET_NAME"],
    [(v, f"VS{v}", f"Value Stream {v}", f"VS{v}") for v in (1, 4, 5, 7, 9)])

L.append("-- Departments (AREA decides the editable fields)")
depts = [("QMM", "Quality Management", "QMM", "Y"), ("QMM-C1", "QMM Customer Quality 1", "QMM", "Y"), ("QMM-C2", "QMM Customer Quality 2", "QMM", "Y"),
         ("MFQ", "Manufacturing Quality", "MFQ", "Y")]
depts += [(f"MFQ{i}", f"Manufacturing Quality {i}", "MFQ", "Y") for i in range(1, 10)]
depts += [("MFO", "Manufacturing Operations", "MFO", "Y")] + [(f"MFO{i}", f"Manufacturing Operations {i}", "MFO", "Y") for i in (1, 4, 5, 7, 9)]
depts += [("LOP", "Logistics Planning", "LOP", "Y"), ("LOP1", "Logistics Planning 1", "LOP", "Y"), ("LOP2", "Logistics Planning 2", "LOP", "Y"),
          ("LOW", "Logistics Warehouse", "LOW", "N"), ("GS/OSD43", "Foreign Trade / Customs", "GS", "N"),
          ("HSE", "Health, Safety & Environment", "HSE", "N"), ("PUQ", "Purchasing Quality", "PUQ", "Y")]
ins("IB_PROCESS_DEPARTMENTS", ["DEPARTMENT_CODE", "NAME", "AREA", "CAN_REQUEST"], depts)

L.append("-- Reasons (Excel list)")
reasons = [(1, "R01", "Packaging change due to customer request", "PACKAGING", "N"),
           (2, "R02", "Packaging change due to planning error", "PACKAGING", "N"),
           (3, "R03", "To change FG P/N with reflash", "REFLASH", "Y"),
           (4, "R04", "To inspect due to possible pallet damage", "INSPECTION", "N"),
           (5, "R05", "To complete a partial pallet", "COMPLETION", "N"),
           (6, "R06", "Inspect due to Customer Quality", "INSPECTION", "N"),
           (7, "R07", "Inspect due to Manufacturing Quality", "INSPECTION", "N"),
           (8, "R08", "Inspect due to Supplier Quality", "INSPECTION", "N"),
           (9, "R09", "Inspect due to incomplete box or pallet", "INSPECTION", "N"),
           (10, "R10", "Inspect due to mistakes in standard pack", "PACKAGING", "N")]
ins("IB_PROCESS_REASONS", ["REASON_ID", "CODE", "DESCRIPTION", "REASON_GROUP", "REQUIRES_NEW_MATERIAL", "SORT_ORDER"],
    [r + (r[0],) for r in reasons])

L.append("-- Workflow status (calculated)")
ins("IB_PROCESS_WORKFLOW_STATUS", ["WORKFLOW_STATUS_ID", "CODE", "NAME", "STAGE_NO", "IS_CLOSED", "SORT_ORDER"], [
    (1, "DRAFT", "Draft", 1, "N", 1), (2, "REQUESTED", "Requested", 1, "N", 2), (3, "IMPORTED", "Imported", 2, "N", 3),
    (4, "IN_REWORK", "In rework", 3, "N", 4), (5, "PENDING_HSE", "Pending HSE", 4, "N", 5), (6, "PENDING_EXPORT", "Pending export", 4, "N", 6),
    (7, "DUTY_RISK", "Duty risk", 5, "N", 7), (8, "EXPORTED", "Exported", 4, "Y", 8), (9, "SCRAPPED", "Scrap confirmed", 4, "Y", 9),
    (10, "CLOSED_DUTY_PAID", "Closed (duty paid)", 5, "Y", 10)])

cats = [(1, "EXPORT", "OUTCOME", None, "N", "Y"), (2, "SCRAP", "OUTCOME", None, "N", "Y"), (3, "INVENTORY", "OUTCOME", None, "N", "Y"),
        (4, "ENVIO NACIONAL", "OUTCOME", "GS", "N", "N"), (5, "SCRAP SIN SALIDA FISICA", "DISCREPANCY", "HSE", "Y", "N"),
        (6, "NO REPORTADO CORRECTAMENTE", "DISCREPANCY", None, "Y", "N"), (7, "NO REPORTADO CON CONO VERDE", "DISCREPANCY", "MFO", "Y", "N"),
        (8, "NO LLEGO CON CONO", "DISCREPANCY", "LOP", "Y", "N"), (9, "MATERIAL CON CONO NO REPORTADO POR LOW", "DISCREPANCY", "LOW", "Y", "N"),
        (10, "MATERIAL NO LLEGO DE ELP", "DISCREPANCY", "LOP", "Y", "N"), (11, "LOW-NO REPORTADO (PLATAFORMA,CONO,RMA)", "DISCREPANCY", "LOW", "Y", "N"),
        (12, "MFO-NO REPORTADO (PLATAFORMA,CONO,RMA)", "DISCREPANCY", "MFO", "Y", "N")]
L.append("-- Status categories = options of the Excel COMMENTS column (exact text)")
ins("IB_PROCESS_STATUS_CATEGORIES", ["STATUS_CATEGORY_ID", "CODE", "KIND", "RESPONSIBLE_AREA", "AFFECTS_DUTY", "IS_AUTOMATIC"], cats)

by_vs = {1: [1, 2, 3, 11, 12, 4, 5], 4: [6, 1, 2, 3, 7, 8, 9, 4, 10], 5: [6, 1, 2, 3, 7, 8, 9], 7: [6, 1, 2, 3, 7, 8, 9], 9: [6, 1, 2, 3, 7, 8, 9, 4]}
L.append("-- Status category list of each VS sheet")
ins("IB_PROCESS_STATUS_CAT_VS", ["VALUE_STREAM_ID", "STATUS_CATEGORY_ID", "SORT_ORDER"],
    [(vs, c, i + 1) for vs, ids in by_vs.items() for i, c in enumerate(ids)])

stage1 = ["QMM_RESPONSIBLE", "REQUESTING_DEPARTMENT", "REQUESTOR_NAME", "REASON_ID", "REASON_DETAIL", "RETURNED_PART_NUMBER",
          "QTY_IMPORTED", "ORIGINAL_HU", "ORIGINAL_BATCH", "PO_DATE", "PO_NUMBER"]
stage3 = ["NEW_PART_NUMBER", "PHYSICAL_DELIVERED_QTY", "NEW_HU", "REWORK_BATCH", "REINSERTION_QTY", "SENT_BACK_DATE",
          "OLD_MATERIAL_DELIVERED_QTY", "SCRAP_QTY", "SCRAP_DATE"]
perms = [("QMM", f, 1) for f in stage1] + [("QMM", "STATUS_CATEGORY_ID", 5)]
perms += [("REQUESTOR", f, 1) for f in stage1 if f not in ("QMM_RESPONSIBLE", "PO_DATE", "PO_NUMBER")]
perms += [("GS", f, 2) for f in ("IMPORT_DATE", "IMPORT_INVOICE", "ELP_JUP1_CROSSING_DATE")] + [("GS", "CUSTOMS_EXPORT", 4)]
perms += [("LOP", "DELIVERY_NUMBER", 2)]
perms += [("MFO", f, 3) for f in stage3] + [("MFO", "GR_NUMBER", 4)]
perms += [("LOW", "LOW_EXPORT_NUMBER", 4), ("LOW", "LOW_EXPORT_DATE", 4)]
perms += [("HSE", "HSE_SCRAP_KG", 4), ("HSE", "HSE_CONFIRMATION_DATE", 4)]
L.append("-- Fields each area edits (Champion / Proxy in their VS). OWNER edits everything and needs no rows.")
ins("IB_PROCESS_FIELD_PERMISSIONS", ["AREA_CODE", "FIELD_NAME", "STAGE_NO"], perms)

L.append("-- Parameters (provisional values: [VALIDATE GS/OSD43])")
ins("IB_PROCESS_PARAMETERS", ["PARAM_KEY", "VALID_FROM", "NUMERIC_VALUE", "DESCRIPTION"], [])
for key, val, desc in [("DUTY_RATE", 0.19, "Duty rate applied to the unreconciled USD value (Excel: *0.19). [VALIDATE GS/OSD43]"),
                       ("IMMEX_LEGAL_TERM_DAYS", 540, "Legal term of the temporary import in days. [VALIDATE GS/OSD43 by regime / pedimento key]"),
                       ("ALERT_WARNING_DAYS_LEFT", 60, "Days before the legal due date for a WARNING alert"),
                       ("ALERT_CRITICAL_DAYS_LEFT", 30, "Days before the legal due date for a CRITICAL alert / duty risk"),
                       ("INTERNAL_SLA_REWORK_DAYS", 15, "Internal deadline: days from crossing to sent-back date"),
                       ("INTERNAL_SLA_EXPORT_DAYS", 7, "Internal deadline: days from delivery to LOW to customs export"),
                       ("INTERNAL_SLA_HSE_DAYS", 10, "Internal deadline: days from scrap date to HSE confirmation"),
                       ("QTY_TOLERANCE_PCS", 0, "Missing pieces tolerated before flagging a discrepancy"),
                       ("CALC_VERSION_ACTIVE", 2, "Calculation engine version")]:
    L.append(f"INSERT INTO IB_PROCESS_PARAMETERS (PARAM_KEY, VALID_FROM, NUMERIC_VALUE, DESCRIPTION) VALUES ({q(key)}, DATE '2024-01-01', {val}, {q(desc)});")
L.append("")

L.append("-- Folio counters")
ins("IB_PROCESS_FOLIO_COUNTERS", ["VALUE_STREAM_ID", "LAST_FOLIO"], [(v, 0) for v in (1, 4, 5, 7, 9)])

L += ["-- First Owner: replace DOMAIN\\OWNER.USER with the Windows user (upper case) and the name, then run.",
      "INSERT INTO IB_PROCESS_USERS (NT_USER, DISPLAY_NAME) VALUES ('DOMAIN\\OWNER.USER', N'Owner name');",
      "INSERT INTO IB_PROCESS_USER_ACCESS (NT_USER, DEPARTMENT_CODE, VALUE_STREAM_ID, FUNCTION_CODE, ASSIGNED_BY) "
      "VALUES ('DOMAIN\\OWNER.USER', NULL, NULL, 'OWNER', 'SETUP');", "", "COMMIT;", ""]

os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w", encoding="utf8").write("\n".join(L))
print("OK ->", os.path.relpath(OUT, ROOT))
