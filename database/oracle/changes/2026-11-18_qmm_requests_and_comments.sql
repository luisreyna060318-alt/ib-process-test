/* =====================================================================
   Expo and Return FG Follow Up (IB Process) - Oracle - CHANGE 2026-11-18 (v0.5.2)
   For a database installed with IB_PROCESS_install.sql of v0.5.1. Run ONCE, connected as the owner of the schema
   (JUP1QMM), BEFORE using the v0.5.2 executable. A new installation with IB_PROCESS_install.sql already includes it.

   1. Field permissions: the request is always made by QMM. The rows of area REQUESTOR (requesting departments MFQ /
      PUQ, which now only read) are removed, and every area of the form (OSD, LOP, MFO, LOW, HSE, besides QMM) can set
      the Status Category (Excel column COMMENTS). Only IB_PROCESS_FIELD_PERMISSIONS changes: no process, pallet, user
      or audit row is touched. The change is written to the audit log as US\RLN8JU.
   2. New table IB_PROCESS_COMMENTS (comments of the Comments tab) with its index, comments and trigger.
   3. Check (last query): what the permissions and the new table look like now.
   ===================================================================== */

SET DEFINE OFF
SET SQLBLANKLINES ON
WHENEVER SQLERROR EXIT ROLLBACK

-- 1. Field permissions
DELETE FROM IB_PROCESS_FIELD_PERMISSIONS WHERE AREA_CODE = 'REQUESTOR';
INSERT INTO IB_PROCESS_FIELD_PERMISSIONS (AREA_CODE, FIELD_NAME, FIELD_LEVEL, STAGE_NO)
SELECT a.AREA_CODE, 'STATUS_CATEGORY_ID', 'PALLET', 5
  FROM (SELECT 'OSD' AS AREA_CODE FROM DUAL UNION ALL SELECT 'LOP' FROM DUAL UNION ALL SELECT 'MFO' FROM DUAL
        UNION ALL SELECT 'LOW' FROM DUAL UNION ALL SELECT 'HSE' FROM DUAL) a
 WHERE NOT EXISTS (SELECT 1 FROM IB_PROCESS_FIELD_PERMISSIONS p WHERE p.AREA_CODE = a.AREA_CODE AND p.FIELD_NAME = 'STATUS_CATEGORY_ID');
INSERT INTO IB_PROCESS_AUDIT_LOG (TABLE_NAME, RECORD_ID, ACTION, FIELD_NAME, OLD_VALUE, NEW_VALUE, NT_USER, APP_VERSION, CHANGE_REASON)
VALUES ('IB_PROCESS_FIELD_PERMISSIONS', 'CHANGE-2026-11-18', 'U', 'AREA_CODE',
        'REQUESTOR edits the request block; Status Category only QMM',
        'REQUESTOR (MFQ, PUQ) read only; Status Category for QMM, OSD, LOP, MFO, LOW, HSE',
        'US\RLN8JU', '0.5.2', 'Change script 2026-11-18: the request is always made by QMM');
COMMIT;

-- 2. Comments of the IB processes
CREATE TABLE IB_PROCESS_COMMENTS (
    COMMENT_ID          NUMBER          GENERATED BY DEFAULT AS IDENTITY,
    PROCESS_ID          NUMBER          NOT NULL,
    COMMENT_TEXT        NVARCHAR2(1000) NOT NULL,
    NT_USER             VARCHAR2(64 CHAR)    NOT NULL,
    DEPARTMENT_CODE     VARCHAR2(20 CHAR),                   -- department of the author (empty for the Owner)
    CREATED_AT          TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT IB_COMM_PK PRIMARY KEY (COMMENT_ID),
    CONSTRAINT IB_COMM_FK_PROCESS FOREIGN KEY (PROCESS_ID) REFERENCES IB_PROCESS_PROCESSES (PROCESS_ID) ON DELETE CASCADE
);
CREATE INDEX IB_COMM_IX_PROCESS ON IB_PROCESS_COMMENTS (PROCESS_ID, CREATED_AT);

COMMENT ON TABLE IB_PROCESS_COMMENTS IS 'Comments on an IB PROCESS (Comments tab); never edited, deleted with the process';

CREATE OR REPLACE TRIGGER IB_PROCESS_COMMENTS_RO
BEFORE UPDATE ON IB_PROCESS_COMMENTS
BEGIN
    RAISE_APPLICATION_ERROR(-20001, 'IB_PROCESS_COMMENTS cannot be edited: add a new comment.');
END;
/

-- 3. Check: STATUS_CATEGORY_ID for 6 areas, REQUESTOR 0 rows, 36 permission rows in total, the table and its trigger exist.
SELECT (SELECT COUNT(*) FROM IB_PROCESS_FIELD_PERMISSIONS WHERE FIELD_NAME = 'STATUS_CATEGORY_ID') AS STATUS_CATEGORY_AREAS_6,
       (SELECT COUNT(*) FROM IB_PROCESS_FIELD_PERMISSIONS WHERE AREA_CODE = 'REQUESTOR') AS REQUESTOR_ROWS_0,
       (SELECT COUNT(*) FROM IB_PROCESS_FIELD_PERMISSIONS) AS PERMISSION_ROWS_36,
       (SELECT COUNT(*) FROM USER_TABLES WHERE TABLE_NAME = 'IB_PROCESS_COMMENTS') AS COMMENTS_TABLE_1,
       (SELECT COUNT(*) FROM USER_TRIGGERS WHERE TRIGGER_NAME = 'IB_PROCESS_COMMENTS_RO' AND STATUS = 'ENABLED') AS COMMENTS_TRIGGER_1
  FROM DUAL;
