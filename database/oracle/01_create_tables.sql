    NT_USER             VARCHAR2(64)    NOT NULL,
    CLIENT_MACHINE      VARCHAR2(64),
    APP_VERSION         VARCHAR2(20),
    CORRELATION_ID      VARCHAR2(36),           -- groups the fields of one save
