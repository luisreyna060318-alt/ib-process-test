    HANDLED_COMMENT     NVARCHAR2(500),
    RESOLVED_AT         TIMESTAMP,
    CONSTRAINT IB_ALERT_PK PRIMARY KEY (ALERT_ID),
    CONSTRAINT IB_ALERT_FK_PR FOREIGN KEY (PALLET_RETURN_ID) REFERENCES IB_PROCESS_PALLET_RETURNS (PALLET_RETURN_ID),
    CONSTRAINT IB_ALERT_CK_TYPE CHECK (ALERT_TYPE IN ('AGING_WARNING','AGING_CRITICAL','LEGAL_EXPIRED','REWORK_SLA','EXPORT_SLA','HSE_SLA','QTY_MISMATCH','COST_PENDING')),
    CONSTRAINT IB_ALERT_CK_SEV CHECK (SEVERITY IN ('INFO','WARNING','CRITICAL')),
    CONSTRAINT IB_ALERT_CK_HANDLED CHECK (HANDLED_AT IS NULL OR (HANDLED_BY IS NOT NULL AND HANDLED_COMMENT IS NOT NULL))
);
CREATE INDEX IB_ALERT_IX_OPEN ON IB_PROCESS_ALERTS (PALLET_RETURN_ID, ALERT_TYPE, RESOLVED_AT);

