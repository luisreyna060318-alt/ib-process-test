/* =====================================================================
   Expo and Return FG Follow Up (IB Process) - Oracle - Script 05: views read by the application
   The inbox, Balance / Duties and Alerts read these views page by page (OFFSET ... FETCH, Oracle 12c+), so the
   application never has to load every process. What depends on the date is calculated HERE, with today's date
   (TRUNC(SYSDATE)) and the parameters in force (IB_PROCESS_PARAMETERS), never taken from a value stored days ago:
     - IMMEX legal due date = ELP -> JuP1 crossing + IMMEX_LEGAL_TERM_DAYS
     - duty risk            = open pieces and (due in ALERT_CRITICAL_DAYS_LEFT days or less, or expired,
                              or missing pieces above QTY_TOLERANCE_PCS, or a status category that affects duty)
     - pallet status        = Draft / Requested / closed as stored (they change only when the data changes and the
                              application saves them); for open pallets with crossing: Duty risk, else In rework /
                              Imported (pieces on the MFO floor), Pending export, Pending HSE
     - duties to pay        = MFO-LOW failure USD x DUTY_RATE
   Same rules as the application (DutyRisk, StatusResolver, IbProcess.StatusOf). Only SELECT; no data is stored.
   ===================================================================== */

-- Parameters in force today (one row). The default is used when a parameter has no active row.
CREATE OR REPLACE VIEW IB_PROCESS_PARAMS_V (IMMEX_TERM_DAYS, CRITICAL_DAYS_LEFT, WARNING_DAYS_LEFT, QTY_TOLERANCE_PCS, DUTY_RATE,
    SLA_REWORK_DAYS, SLA_EXPORT_DAYS, SLA_HSE_DAYS) AS
SELECT NVL((SELECT MAX(NUMERIC_VALUE) KEEP (DENSE_RANK LAST ORDER BY VALID_FROM) FROM IB_PROCESS_PARAMETERS
             WHERE PARAM_KEY = 'IMMEX_LEGAL_TERM_DAYS' AND NUMERIC_VALUE IS NOT NULL
               AND VALID_FROM <= TRUNC(SYSDATE) AND (VALID_TO IS NULL OR VALID_TO >= TRUNC(SYSDATE))), 540),
       NVL((SELECT MAX(NUMERIC_VALUE) KEEP (DENSE_RANK LAST ORDER BY VALID_FROM) FROM IB_PROCESS_PARAMETERS
             WHERE PARAM_KEY = 'ALERT_CRITICAL_DAYS_LEFT' AND NUMERIC_VALUE IS NOT NULL
               AND VALID_FROM <= TRUNC(SYSDATE) AND (VALID_TO IS NULL OR VALID_TO >= TRUNC(SYSDATE))), 30),
       NVL((SELECT MAX(NUMERIC_VALUE) KEEP (DENSE_RANK LAST ORDER BY VALID_FROM) FROM IB_PROCESS_PARAMETERS
             WHERE PARAM_KEY = 'ALERT_WARNING_DAYS_LEFT' AND NUMERIC_VALUE IS NOT NULL
               AND VALID_FROM <= TRUNC(SYSDATE) AND (VALID_TO IS NULL OR VALID_TO >= TRUNC(SYSDATE))), 60),
       NVL((SELECT MAX(NUMERIC_VALUE) KEEP (DENSE_RANK LAST ORDER BY VALID_FROM) FROM IB_PROCESS_PARAMETERS
             WHERE PARAM_KEY = 'QTY_TOLERANCE_PCS' AND NUMERIC_VALUE IS NOT NULL
               AND VALID_FROM <= TRUNC(SYSDATE) AND (VALID_TO IS NULL OR VALID_TO >= TRUNC(SYSDATE))), 0),
       NVL((SELECT MAX(NUMERIC_VALUE) KEEP (DENSE_RANK LAST ORDER BY VALID_FROM) FROM IB_PROCESS_PARAMETERS
             WHERE PARAM_KEY = 'DUTY_RATE' AND NUMERIC_VALUE IS NOT NULL
               AND VALID_FROM <= TRUNC(SYSDATE) AND (VALID_TO IS NULL OR VALID_TO >= TRUNC(SYSDATE))), 0.19),
       NVL((SELECT MAX(NUMERIC_VALUE) KEEP (DENSE_RANK LAST ORDER BY VALID_FROM) FROM IB_PROCESS_PARAMETERS
             WHERE PARAM_KEY = 'INTERNAL_SLA_REWORK_DAYS' AND NUMERIC_VALUE IS NOT NULL
               AND VALID_FROM <= TRUNC(SYSDATE) AND (VALID_TO IS NULL OR VALID_TO >= TRUNC(SYSDATE))), 15),
       NVL((SELECT MAX(NUMERIC_VALUE) KEEP (DENSE_RANK LAST ORDER BY VALID_FROM) FROM IB_PROCESS_PARAMETERS
             WHERE PARAM_KEY = 'INTERNAL_SLA_EXPORT_DAYS' AND NUMERIC_VALUE IS NOT NULL
               AND VALID_FROM <= TRUNC(SYSDATE) AND (VALID_TO IS NULL OR VALID_TO >= TRUNC(SYSDATE))), 7),
       NVL((SELECT MAX(NUMERIC_VALUE) KEEP (DENSE_RANK LAST ORDER BY VALID_FROM) FROM IB_PROCESS_PARAMETERS
             WHERE PARAM_KEY = 'INTERNAL_SLA_HSE_DAYS' AND NUMERIC_VALUE IS NOT NULL
               AND VALID_FROM <= TRUNC(SYSDATE) AND (VALID_TO IS NULL OR VALID_TO >= TRUNC(SYSDATE))), 10)
  FROM DUAL;

-- One row per pallet, with the data of its process and what depends on today.
CREATE OR REPLACE VIEW IB_PROCESS_PALLETS_V (PALLET_ID, PROCESS_ID, LINE_NO, PALLET_CODE, VALUE_STREAM_ID, FOLIO_NUMBER, FOLIO_CODE,
    RETURNED_PART_NUMBER, QTY_IMPORTED, MM60_UNIT_COST_USD, SAP_TOTAL_USD, ORIGINAL_HU, ORIGINAL_BATCH, PO_NUMBER, CUSTOMS_EXPORT,
    STATUS_CATEGORY_CODE, SENT_BACK_DATE, SCRAP_DATE, QTY_OPEN_FLOOR, QTY_PENDING_EXPORT, QTY_PENDING_HSE, QTY_MISSING, QTY_OPEN_TOTAL,
    MFO_INVENTORY_USD, HSE_SCRAP_USD, MFO_LOW_FAILURE_USD, GENERAL_BALANCE_USD, DUTIES_TO_PAY_USD, CROSSING_DATE, LEGAL_DUE_DATE,
    DAYS_TO_DUE, IS_DUTY_RISK, WORKFLOW_STATUS_ID, IS_OPEN, IS_LEGACY, DATA_QUALITY_FLAGS) AS
SELECT r.PALLET_ID, r.PROCESS_ID, r.LINE_NO, r.FOLIO_CODE || '-' || LPAD(TO_CHAR(r.LINE_NO), 2, '0'), r.VALUE_STREAM_ID,
       r.FOLIO_NUMBER, r.FOLIO_CODE, r.RETURNED_PART_NUMBER, r.QTY_IMPORTED, r.MM60_UNIT_COST_USD, r.SAP_TOTAL_USD, r.ORIGINAL_HU,
       r.ORIGINAL_BATCH, r.PO_NUMBER, r.CUSTOMS_EXPORT, r.STATUS_CATEGORY_CODE, r.SENT_BACK_DATE, r.SCRAP_DATE, r.QTY_OPEN_FLOOR,
       r.QTY_PENDING_EXPORT, r.QTY_PENDING_HSE, r.QTY_MISSING, r.QTY_OPEN_TOTAL, r.MFO_INVENTORY_USD, r.HSE_SCRAP_USD,
       r.MFO_LOW_FAILURE_USD, r.GENERAL_BALANCE_USD, r.DUTIES_TO_PAY_USD, r.CROSSING_DATE, r.LEGAL_DUE_DATE,
       CASE WHEN r.STATUS_ID NOT IN (8, 9, 10) THEN r.LEGAL_DUE_DATE - TRUNC(SYSDATE) END,
       r.IS_DUTY_RISK, r.STATUS_ID, CASE WHEN r.STATUS_ID IN (8, 9, 10) THEN 'N' ELSE 'Y' END, r.IS_LEGACY, r.DATA_QUALITY_FLAGS
  FROM (SELECT k.*,
               CASE WHEN k.STORED_STATUS_ID IN (1, 2, 8, 9, 10) OR k.CROSSING_DATE IS NULL OR k.QTY_OPEN_TOTAL = 0 THEN k.STORED_STATUS_ID
                    WHEN k.IS_DUTY_RISK = 'Y' THEN 7
                    WHEN k.QTY_OPEN_FLOOR > 0 THEN CASE WHEN k.REWORK_STARTED = 'Y' THEN 4 ELSE 3 END
                    WHEN k.QTY_PENDING_EXPORT > 0 THEN 6
                    ELSE 5 END AS STATUS_ID
          FROM (SELECT b.*,
                       CASE WHEN b.CROSSING_DATE IS NOT NULL AND b.QTY_OPEN_TOTAL > 0
                             AND (b.LEGAL_DUE_DATE - TRUNC(SYSDATE) <= b.CRITICAL_DAYS_LEFT OR b.QTY_MISSING > b.QTY_TOLERANCE_PCS
                                  OR b.AFFECTS_DUTY = 'Y')
                            THEN 'Y' ELSE 'N' END AS IS_DUTY_RISK
                  FROM (SELECT pal.PALLET_ID, pal.PROCESS_ID, pal.LINE_NO, prc.VALUE_STREAM_ID, prc.FOLIO_NUMBER, prc.FOLIO_CODE,
                               pal.RETURNED_PART_NUMBER, pal.QTY_IMPORTED, pal.MM60_UNIT_COST_USD, pal.SAP_TOTAL_USD, pal.ORIGINAL_HU,
                               pal.ORIGINAL_BATCH, pal.PO_NUMBER, pal.CUSTOMS_EXPORT, scat.CODE AS STATUS_CATEGORY_CODE,
                               pal.SENT_BACK_DATE, pal.SCRAP_DATE, pal.QTY_OPEN_FLOOR, pal.QTY_PENDING_EXPORT, pal.QTY_PENDING_HSE,
                               pal.QTY_MISSING,
                               pal.QTY_OPEN_FLOOR + pal.QTY_PENDING_EXPORT + pal.QTY_PENDING_HSE + pal.QTY_MISSING AS QTY_OPEN_TOTAL,
                               pal.MFO_INVENTORY_USD, pal.HSE_SCRAP_USD, pal.MFO_LOW_FAILURE_USD, pal.GENERAL_BALANCE_USD,
                               ROUND(pal.MFO_LOW_FAILURE_USD * prm.DUTY_RATE, 2) AS DUTIES_TO_PAY_USD,
                               prc.ELP_JUP1_CROSSING_DATE AS CROSSING_DATE,
                               TRUNC(prc.ELP_JUP1_CROSSING_DATE) + prm.IMMEX_TERM_DAYS AS LEGAL_DUE_DATE,
                               prm.CRITICAL_DAYS_LEFT, prm.QTY_TOLERANCE_PCS, NVL(scat.AFFECTS_DUTY, 'N') AS AFFECTS_DUTY,
                               pal.WORKFLOW_STATUS_ID AS STORED_STATUS_ID,
                               CASE WHEN pal.NEW_PART_NUMBER IS NOT NULL OR pal.NEW_HU IS NOT NULL OR pal.REINSERTION_QTY IS NOT NULL
                                         OR NVL(pal.SCRAP_QTY, 0) > 0 OR pal.SENT_BACK_DATE IS NOT NULL THEN 'Y' ELSE 'N' END AS REWORK_STARTED,
                               pal.IS_LEGACY, pal.DATA_QUALITY_FLAGS
                          FROM IB_PROCESS_PALLETS pal
                          JOIN IB_PROCESS_PROCESSES prc ON prc.PROCESS_ID = pal.PROCESS_ID
                          CROSS JOIN IB_PROCESS_PARAMS_V prm
                          LEFT JOIN IB_PROCESS_STATUS_CATEGORIES scat ON scat.STATUS_CATEGORY_ID = pal.STATUS_CATEGORY_ID) b) k) r;

-- Inbox: one row per IB PROCESS with the totals of its pallets. Status of the process: Draft without pallets; Duty risk if
-- any pallet is; else the least advanced open pallet; all closed: Closed (duty paid) if any, else Exported if any, else Scrap.
CREATE OR REPLACE VIEW IB_PROCESS_INBOX_V (PROCESS_ID, VALUE_STREAM_ID, FOLIO_NUMBER, FOLIO_CODE, PROCESS_STATUS_ID, IS_CLOSED,
    PALLET_COUNT, QTY_IMPORTED, FIRST_PART_NUMBER, PART_NUMBER_COUNT, FIRST_PO_NUMBER, PO_NUMBER_COUNT, SAP_TOTAL_USD,
    GENERAL_BALANCE_USD, DUTIES_TO_PAY_USD, IS_DUTY_RISK, CROSSING_DATE, DAYS_IN_JUP1, NEAREST_DUE_DATE, DAYS_TO_DUE,
    QMM_RESPONSIBLE, REQUESTOR_NAME, REQUESTING_DEPARTMENT, IMPORT_INVOICE, DELIVERY_NUMBER, IS_LEGACY, OPEN_FINDINGS,
    DATA_QUALITY_FLAGS) AS
SELECT s.PROCESS_ID, s.VALUE_STREAM_ID, s.FOLIO_NUMBER, s.FOLIO_CODE, s.PROCESS_STATUS_ID,
       CASE WHEN s.PROCESS_STATUS_ID IN (8, 9, 10) THEN 'Y' ELSE 'N' END,
       s.PALLET_COUNT, s.QTY_IMPORTED, s.FIRST_PART_NUMBER, s.PART_NUMBER_COUNT, s.FIRST_PO_NUMBER, s.PO_NUMBER_COUNT, s.SAP_TOTAL_USD,
       s.GENERAL_BALANCE_USD, s.DUTIES_TO_PAY_USD, s.IS_DUTY_RISK, s.CROSSING_DATE, TRUNC(SYSDATE) - TRUNC(s.CROSSING_DATE),
       s.NEAREST_DUE_DATE, CASE WHEN s.PROCESS_STATUS_ID NOT IN (8, 9, 10) THEN s.NEAREST_DUE_DATE - TRUNC(SYSDATE) END,
       s.QMM_RESPONSIBLE, s.REQUESTOR_NAME, s.REQUESTING_DEPARTMENT, s.IMPORT_INVOICE, s.DELIVERY_NUMBER, s.IS_LEGACY,
       s.OPEN_FINDINGS, s.DATA_QUALITY_FLAGS
  FROM (SELECT prc.PROCESS_ID, prc.VALUE_STREAM_ID, prc.FOLIO_NUMBER, prc.FOLIO_CODE,
               CASE WHEN NVL(a.PALLET_COUNT, 0) = 0 THEN 1
                    WHEN a.ANY_RISK_STATUS = 1 THEN 7
                    WHEN a.MIN_OPEN_STATUS IS NOT NULL THEN a.MIN_OPEN_STATUS
                    WHEN a.ANY_DUTY_PAID = 1 THEN 10
                    WHEN a.ANY_EXPORTED = 1 THEN 8
                    ELSE 9 END AS PROCESS_STATUS_ID,
               NVL(a.PALLET_COUNT, 0) AS PALLET_COUNT, NVL(a.QTY_IMPORTED, 0) AS QTY_IMPORTED, a.FIRST_PART_NUMBER,
               NVL(a.PART_NUMBER_COUNT, 0) AS PART_NUMBER_COUNT, a.FIRST_PO_NUMBER, NVL(a.PO_NUMBER_COUNT, 0) AS PO_NUMBER_COUNT,
               NVL(a.SAP_TOTAL_USD, 0) AS SAP_TOTAL_USD, NVL(a.GENERAL_BALANCE_USD, 0) AS GENERAL_BALANCE_USD,
               NVL(a.DUTIES_TO_PAY_USD, 0) AS DUTIES_TO_PAY_USD, NVL(a.IS_DUTY_RISK, 'N') AS IS_DUTY_RISK,
               prc.ELP_JUP1_CROSSING_DATE AS CROSSING_DATE, a.NEAREST_DUE_DATE, prc.QMM_RESPONSIBLE, prc.REQUESTOR_NAME,
               prc.REQUESTING_DEPARTMENT, prc.IMPORT_INVOICE, prc.DELIVERY_NUMBER, prc.IS_LEGACY, prc.OPEN_FINDINGS,
               a.DATA_QUALITY_FLAGS
          FROM IB_PROCESS_PROCESSES prc
          LEFT JOIN (SELECT v.PROCESS_ID, COUNT(*) AS PALLET_COUNT, SUM(v.QTY_IMPORTED) AS QTY_IMPORTED,
                            MIN(v.RETURNED_PART_NUMBER) AS FIRST_PART_NUMBER, COUNT(DISTINCT v.RETURNED_PART_NUMBER) AS PART_NUMBER_COUNT,
                            MIN(v.PO_NUMBER) AS FIRST_PO_NUMBER, COUNT(DISTINCT v.PO_NUMBER) AS PO_NUMBER_COUNT,
                            SUM(v.SAP_TOTAL_USD) AS SAP_TOTAL_USD, SUM(v.GENERAL_BALANCE_USD) AS GENERAL_BALANCE_USD,
                            SUM(v.DUTIES_TO_PAY_USD) AS DUTIES_TO_PAY_USD, MAX(v.IS_DUTY_RISK) AS IS_DUTY_RISK,
                            MAX(CASE WHEN v.WORKFLOW_STATUS_ID = 7 THEN 1 ELSE 0 END) AS ANY_RISK_STATUS,
                            MIN(CASE WHEN v.IS_OPEN = 'Y' THEN v.WORKFLOW_STATUS_ID END) AS MIN_OPEN_STATUS,
                            MAX(CASE WHEN v.WORKFLOW_STATUS_ID = 10 THEN 1 ELSE 0 END) AS ANY_DUTY_PAID,
                            MAX(CASE WHEN v.WORKFLOW_STATUS_ID = 8 THEN 1 ELSE 0 END) AS ANY_EXPORTED,
                            MIN(CASE WHEN v.IS_OPEN = 'Y' THEN v.LEGAL_DUE_DATE END) AS NEAREST_DUE_DATE,
                            MIN(v.DATA_QUALITY_FLAGS) AS DATA_QUALITY_FLAGS
                       FROM IB_PROCESS_PALLETS_V v
                      GROUP BY v.PROCESS_ID) a ON a.PROCESS_ID = prc.PROCESS_ID) s;

-- Users and Access as the Owner sees it: one row per user and department (active access only) with one column per
-- Value Stream holding the function there (VIEWER, MEMBER, PROXY, CHAMPION; empty = no access). The table keeps one
-- row per user x department x VS with its history (VALID_FROM / VALID_TO); this view is the readable matrix for reviews
-- and audits. OTHER_VS_ROWS > 0 means a Value Stream not listed here: add its column (the table does not change).
CREATE OR REPLACE VIEW IB_PROCESS_USER_ACCESS_V (NT_USER, DISPLAY_NAME, DEPARTMENT_CODE, IS_OWNER, VS1_FUNCTION, VS4_FUNCTION,
    VS5_FUNCTION, VS7_FUNCTION, VS9_FUNCTION, OTHER_VS_ROWS, ACCESS_ROWS, LAST_CHANGE_AT) AS
SELECT a.NT_USER, u.DISPLAY_NAME, a.DEPARTMENT_CODE,
       MAX(CASE WHEN a.FUNCTION_CODE = 'OWNER' THEN 'Y' ELSE 'N' END),
       MAX(CASE WHEN a.VALUE_STREAM_ID = 1 THEN a.FUNCTION_CODE END),
       MAX(CASE WHEN a.VALUE_STREAM_ID = 4 THEN a.FUNCTION_CODE END),
       MAX(CASE WHEN a.VALUE_STREAM_ID = 5 THEN a.FUNCTION_CODE END),
       MAX(CASE WHEN a.VALUE_STREAM_ID = 7 THEN a.FUNCTION_CODE END),
       MAX(CASE WHEN a.VALUE_STREAM_ID = 9 THEN a.FUNCTION_CODE END),
       SUM(CASE WHEN a.VALUE_STREAM_ID NOT IN (1, 4, 5, 7, 9) THEN 1 ELSE 0 END),
       COUNT(*), MAX(a.VALID_FROM)
  FROM IB_PROCESS_USER_ACCESS a
  JOIN IB_PROCESS_USERS u ON u.NT_USER = a.NT_USER
 WHERE a.VALID_TO IS NULL
 GROUP BY a.NT_USER, u.DISPLAY_NAME, a.DEPARTMENT_CODE;
